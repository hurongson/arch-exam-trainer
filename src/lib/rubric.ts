/**
 * 一级注册建筑师建筑方案设计（作图题）评分标准
 * 基于官方评分标准的结构化版本，用于 AI 评图
 */

export const DEFAULT_RUBRIC = `
# 一级注册建筑师建筑方案设计（作图题）评分标准（总分100分）

## 一、总平面设计（15分）
1. 建筑布局合理，与场地关系正确（5分）
2. 出入口位置合理，人车分流（3分）
3. 停车场（库）布局合理，车位数量满足要求（3分）
4. 道路系统、消防车道满足规范（2分）
5. 绿化、广场等室外空间布局（2分）

## 二、功能分区与平面布局（35分）
1. 功能分区明确，动静分区、洁污分区、内外分区合理（10分）
2. 主要功能空间布局合理，面积分配满足要求（8分）
3. 辅助空间、后勤空间布局合理（5分）
4. 公共空间（门厅、中庭、走廊等）布局合理（4分）
5. 垂直交通（楼梯、电梯）位置合理，数量满足规范（4分）
6. 卫生间布局合理，位置方便（4分）

## 三、流线组织（20分）
1. 主要使用流线清晰顺畅，无交叉（8分）
2. 次要流线、后勤流线独立清晰（5分）
3. 特殊流线（如医患、人货、观众/演员等）严格分离（5分）
4. 疏散流线满足防火规范（2分）

## 四、空间设计与规范（15分）
1. 空间尺度合理，层高满足要求（3分）
2. 采光通风满足功能需求（3分）
3. 防火分区、疏散距离、安全出口满足规范（5分）
4. 无障碍设计满足要求（2分）
5. 结构选型合理，柱网规整（2分）

## 五、图面表达与完整性（15分）
1. 图纸内容完整，总平面、各层平面齐全（5分）
2. 尺寸标注、轴号、标高、房间名称标注完整（4分）
3. 图面整洁，线条清晰，比例正确（3分）
4. 指北针、比例尺、图名等图面要素完整（3分）

## 扣分说明
- 严重违反规范（防火、疏散、无障碍等）每项扣5-10分
- 功能流线严重交叉每项扣3-5分
- 缺图或图纸严重不完整扣10-20分
- 面积超标或不足超过10%扣2-5分
`;

/** 根据建筑类型生成针对性评分标准 */
export function getRubricByType(buildingType: string): string {
  const typeSpecific: Record<string, string> = {
    交通: `
## 交通建筑特殊要求
- 旅客流线（出发/到达/换乘）必须清晰分离，占流线组织权重的60%
- 站台/车位/停机位布局必须与建筑紧密联系
- 行李/货物流线必须独立，不得与旅客流线交叉
- 大跨度空间结构选型合理
`,
    医养: `
## 医疗/养老建筑特殊要求
- 医患分流必须严格执行，医生通道与患者通道完全分离
- 护理单元布局合理，护士站视野覆盖整个护理单元
- 病房朝南，日照满足规范
- 洁净区与污染区分区明确
- 无障碍设计要求更高
`,
    服务: `
## 服务类建筑特殊要求
- 公众区、办公区、特殊功能区严格分离
- 多条流线（公众/工作人员/特殊人群）互不干扰
- 安保空间、安检空间布局合理
- 礼宾/接待空间位置醒目
`,
    文体: `
## 文化/体育建筑特殊要求
- 观众流线与运动员/工作人员流线分离
- 大空间（展厅/影厅/赛场）布局合理，结构选型正确
- 疏散流线满足大空间人员密集要求
- 声光隔离满足功能要求
- 参观流线连贯不回头
`,
    商业: `
## 商业建筑特殊要求
- 顾客流线清晰，购物动线合理
- 进货/后勤流线完全独立
- 营业区与仓储区分区明确
- 收银/出入口布局合理
- 标准层（如客房）效率高
`,
    居住: `
## 居住建筑特殊要求
- 户型设计合理，动静分区
- 日照间距满足规范
- 公共空间（电梯厅、走廊）布局合理
- 交通核高效
`,
    工业科研: `
## 工业/科研建筑特殊要求
- 科研与生产流线分离
- 货物装卸场地布局合理
- 洁净区与普通区分区
- 办公与生产联系便捷
- 设备空间、管道井布局合理
`,
  };

  return DEFAULT_RUBRIC + (typeSpecific[buildingType] || '');
}
